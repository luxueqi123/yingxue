export function cleanedCaseMediaBinding(id: string, renditionSha256?: string) {
    const canonicalId = /^[a-f0-9]{32}$/.test(id) ? `case-${id}` : id;
    const original = Object.hasOwn(cleanedMediaBindings, canonicalId) ? cleanedMediaBindings[canonicalId] : undefined;
    const released = Object.hasOwn(releasedWebMediaBindings, canonicalId) ? releasedWebMediaBindings[canonicalId] : undefined;
    const binding = renditionSha256 && released?.sha256 === renditionSha256 ? { ...original, ...released } : original ?? released;
    return binding ? {
        ...binding,
        path: binding.path ?? `/production-library/case-media/${canonicalId.slice(5)}-${binding.sha256}.mp4`,
        coverPath: binding.coverSha256 ? `/production-library/covers/cases/${canonicalId.slice(5)}-${binding.coverSha256}.webp` : undefined,
    } : undefined;
}

export function resolveProductionMedia(item: ProductionItem): { local: string | undefined; remote: string | undefined } {
    const binding = cleanedCaseMediaBinding(item.id, item.localMediaInfo?.sha256);
    if (binding) {
        const valid = !binding.playbackHeld && item.localMedia === binding.path && item.localMediaInfo?.sha256 === binding.sha256
            && item.localMediaInfo.bytes === binding.bytes;
        return { local: valid ? binding.path : undefined, remote: undefined };
    }
    const source = item.localMedia;
    const hash = item.localMediaInfo?.sha256;
    return { local: source && hash ? `${source}?sha256=${encodeURIComponent(hash)}` : source, remote: item.media };
}

export function resolveProductionCover(item: ProductionItem): { local: string | undefined; remote: string | undefined } {
    const binding = cleanedCaseMediaBinding(item.id);
    if (binding?.coverPath) return { local: binding.coverPath, remote: undefined };
    if (!item.localCover) {
        const thumbnail = caseCoverThumbnail(item.id, item.cover);
        if (thumbnail) return { local: thumbnail, remote: undefined };
    }
    return { local: item.localCover, remote: item.cover };
}

export function enforceCleanedCaseMedia(item: ProductionItem): ProductionItem {
    if (!cleanedCaseMediaBinding(item.id)) return item;
    const { local } = resolveProductionMedia(item);
    const cover = resolveProductionCover(item);
    return { ...item, media: undefined, localMedia: local,
        localCover: cover.local, cover: cover.remote,
        localMediaInfo: local ? item.localMediaInfo : undefined, mediaStatus: local ? "local" : "unavailable" };
}
